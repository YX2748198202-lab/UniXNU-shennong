#!/usr/bin/env bash
# Build the shennong UEFI firmware volume (SILICIUM_UEFI.fd) from a Mu-Silicium tree.
#
# This is the reproducible equivalent of `build_uefi.py -d shennong`, without the
# edk2-pytool "external dependency" stage: that stage wants Mu-Basetools / mu_nasm /
# onecrypto-bin release assets that github.com releases do not serve to this host.
# Everything it would install already exists here (BaseTools built locally, system
# nasm/iasl, secure boot off), so the EDK II build is driven directly.
#
# Inputs (override with the matching environment variable):
#   UEFI_TREE   Mu-Silicium / uefi-sheng checkout      (default /home/yoox/android/sources/uefi-sheng)
#   UNIXNU_TREE UniXNU framework checkout              (default /home/yoox/android/workspace/UniXNU-pin)
#   TARGET      DEBUG | RELEASE                        (default DEBUG)
#   OUT_DIR     where the FD is copied                 (default ../../artifacts/UniXNU-shennong/firmware)
#
# The platform package itself is generated by scripts/make-shennong-uefi-pkg.py; run that
# first (it is idempotent).
set -euo pipefail

UEFI_TREE="${UEFI_TREE:-/home/yoox/android/sources/uefi-sheng}"
UNIXNU_TREE="${UNIXNU_TREE:-/home/yoox/android/workspace/UniXNU-pin}"
TARGET="${TARGET:-DEBUG}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT_DIR="${OUT_DIR:-$HERE/../../../artifacts/UniXNU-shennong/firmware}"
DEVICE=shennong
PACKAGE=shennongPkg

FD_BASE=0xa7100000
FD_SIZE=0x300000
FD_BLOCKS=0x300

[ -d "$UEFI_TREE/Mu_Basecore/BaseTools" ] || { echo "not a Mu tree: $UEFI_TREE" >&2; exit 1; }
[ -d "$UEFI_TREE/Platforms/Xiaomi/$PACKAGE" ] || { echo "run scripts/make-shennong-uefi-pkg.py first" >&2; exit 1; }
[ -d "$UEFI_TREE/DarwinBootPkg" ] || { echo "missing $UEFI_TREE/DarwinBootPkg (UniXNU/DarwinBoot)" >&2; exit 1; }
[ -d "$UNIXNU_TREE/package/UniXNUPkg" ] || { echo "missing $UNIXNU_TREE/package/UniXNUPkg" >&2; exit 1; }

export WORKSPACE="$UEFI_TREE"
export EDK_TOOLS_PATH="$UEFI_TREE/Mu_Basecore/BaseTools"
export CONF_PATH="$UEFI_TREE/Conf"
export PACKAGES_PATH="$UEFI_TREE/Platforms/Xiaomi:$UEFI_TREE:$UEFI_TREE/Mu_Basecore:$UEFI_TREE/Common/Mu:$UEFI_TREE/Common/Mu_OEM_Sample:$UEFI_TREE/Silicon/Qualcomm:$UEFI_TREE/Silicon/Silicium:$UEFI_TREE/Silicium-ACPI:$UEFI_TREE/Silicium-ACPI/Platforms/OnePlus:$UNIXNU_TREE/package"
export PYTHONPATH="$EDK_TOOLS_PATH/Source/Python"
export PATH="$EDK_TOOLS_PATH/BinWrappers/PosixLike:$EDK_TOOLS_PATH/Source/C/bin:$PATH"
[ -x "$UEFI_TREE/.venv/bin/python" ] && export PATH="$UEFI_TREE/.venv/bin:$PATH"
export CLANG_BIN="${CLANG_BIN:-/usr/bin/}"
export PYTHON_COMMAND="${PYTHON_COMMAND:-python3}"

# EDK II shells out to `python` from the BaseTools wrappers.
command -v python >/dev/null || { echo "no 'python' on PATH; set PATH to a venv with a python shim" >&2; exit 1; }
for tool in GenFw GenFfs GenFv GenSec EfiRom VfrCompile LzmaCompress BrotliCompress; do
  [ -x "$EDK_TOOLS_PATH/Source/C/bin/$tool" ] || { echo "BaseTools/$tool missing; run: make -C $EDK_TOOLS_PATH/Source/C -j\$(nproc) $tool" >&2; exit 1; }
done

mkdir -p "$CONF_PATH"
for name in target tools_def build_rule; do
  [ -f "$CONF_PATH/$name.txt" ] || cp "$EDK_TOOLS_PATH/Conf/$name.template" "$CONF_PATH/$name.txt"
done

LOG_DIR="${LOG_DIR:-$OUT_DIR/logs}"
mkdir -p "$LOG_DIR"
LOG="$LOG_DIR/firmware-$DEVICE-$TARGET.log"

echo "WORKSPACE    = $WORKSPACE"
echo "PACKAGES_PATH= $PACKAGES_PATH"
echo "log          = $LOG"

python3 "$EDK_TOOLS_PATH/Source/Python/build/build.py" \
  -p "$PACKAGE/$DEVICE.dsc" -a AARCH64 -b "$TARGET" -t CLANGPDB -n "$(nproc)" \
  -D FD_BASE=$FD_BASE -D FD_SIZE=$FD_SIZE -D FD_BLOCKS=$FD_BLOCKS \
  -D DEVICE_MODEL=0 -D ENABLE_SECUREBOOT=0 2>&1 | tee "$LOG"

FD="$UEFI_TREE/Build/${PACKAGE}/${TARGET}_CLANGPDB/FV/SILICIUM_UEFI.fd"
[ -f "$FD" ] || { echo "build finished without $FD" >&2; exit 1; }
size=$(stat -c %s "$FD")
if [ "$size" -ne $((FD_SIZE)) ]; then
  echo "FD is $size bytes, expected $((FD_SIZE))" >&2
  exit 1
fi

mkdir -p "$OUT_DIR"
cp "$FD" "$OUT_DIR/SILICIUM_UEFI-$DEVICE-$TARGET.fd"
sha256sum "$FD" | tee "$OUT_DIR/SILICIUM_UEFI-$DEVICE-$TARGET.fd.sha256"
echo "FD ok: $size bytes (0x$(printf %X "$size"))"
