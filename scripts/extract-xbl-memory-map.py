#!/usr/bin/env python3
"""Extract the DDR memory map from a stock xbl_config blob.

The UEFI platform's MemoryMapLib must describe exactly the regions the bootloader
(XBL) already carved out of DRAM: FD window, UEFI heap, kernel window, the
carveouts (PIL, TZApps, display, demura, DBI dump) and the SMEM/DT windows. Guessing
them invites the firmware to hand a driver memory another subsystem still owns.

xbl_config carries that map as a serialized list. Each entry is big-endian:

    u32 tag        0x000000B9
    u64 base
    u64 size
    u32 version
    u32 name_len
    u32 marker     0x00000956  ("V")
    char name[name_len]  padded to 4
    repeated attribute triples
        u32 0x00000003
        u32 value_len
        u32 attribute_id   (0x5F '_', 0x71 'q', 0x7A 'z', ...)
        u8  value[value_len]

Cross-checked against the port of the sibling Xiaomi SM8650 device (houji), whose
generated MemoryMapLib.c carries the same eight carveouts with the same numbers, and
whose `ResourceAttribute` column is byte-for-byte the `_` attribute word here.

Usage:
    extract-xbl-memory-map.py xbl_config.bin            # human table
    extract-xbl-memory-map.py xbl_config.bin --json     # rows as JSON
    extract-xbl-memory-map.py xbl_config.bin --toml     # rows as TOML
"""
import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

TAG = 0x000000B9
MARKER = 0x00000956
ATTR_HEADER = 0x00000003
RAM_BASE = 0x8000_0000

ATTR_NAMES = {0x5F: "attr", 0x71: "flag_q", 0x7A: "flag_z"}


def u32(data, offset):
    return struct.unpack_from(">I", data, offset)[0]


def u64(data, offset):
    return struct.unpack_from(">Q", data, offset)[0]


def parse_entries(data):
    """Yield one dict per serialized region.

    The records are not 4-byte aligned in this blob, so the scan is byte-wise.
    """
    tag = struct.pack(">I", TAG)
    offset = 0
    while True:
        offset = data.find(tag, offset)
        if offset < 0 or offset + 32 > len(data):
            return
        if u32(data, offset + 28) != MARKER:
            offset += 1
            continue
        base = u64(data, offset + 4)
        size = u64(data, offset + 12)
        version = u32(data, offset + 20)
        name_len = u32(data, offset + 24)
        if not 0 < name_len <= 32:
            offset += 1
            continue
        name_end = offset + 32 + name_len
        if name_end > len(data):
            return
        raw = data[offset + 32:name_end].rstrip(b"\x00")
        if not raw or not all(0x20 <= byte < 0x7F for byte in raw):
            offset += 1
            continue
        entry = {
            "name": raw.decode("ascii"),
            "base": base,
            "size": size,
            "version": version,
            "offset": offset,
            "attributes": {},
        }
        cursor = name_end
        while cursor + 16 <= len(data) and u32(data, cursor) == ATTR_HEADER:
            value_len = u32(data, cursor + 4)
            attribute_id = u32(data, cursor + 8)
            if value_len > 16 or cursor + 16 + value_len > len(data):
                break
            value = int.from_bytes(data[cursor + 12:cursor + 12 + value_len], "big")
            entry["attributes"].setdefault(ATTR_NAMES.get(attribute_id, f"0x{attribute_id:02X}"), value)
            cursor += 12 + ((value_len + 3) & ~3)
        offset = name_end
        yield entry


SPAN_REGIONS = {"DDR", "NOMAP"}


def check(rows, source):
    """Reject a blob that does not look like an xbl_config memory map.

    DDR/NOMAP describe whole address ranges, so they legitimately contain the
    carveouts; only the carveouts themselves must be disjoint.
    """
    if not rows:
        raise SystemExit(f"{source}: no memory regions found (not an xbl_config?)")
    overlaps = []
    ddr = [row for row in rows if row["base"] >= RAM_BASE and row["name"] not in SPAN_REGIONS]
    ordered = sorted(ddr, key=lambda row: row["base"])
    for left, right in zip(ordered, ordered[1:]):
        if left["base"] + left["size"] > right["base"]:
            overlaps.append((left["name"], right["name"]))
    if overlaps:
        raise SystemExit(f"{source}: regions overlap: {overlaps}")
    return rows


def as_json(rows, source, digest):
    return json.dumps({"source": source, "sha256": digest, "regions": rows}, indent=2) + "\n"


def as_toml(rows, source, digest):
    out = [f'# generated by scripts/extract-xbl-memory-map.py from {source}',
           f'# sha256 = "{digest}"',
           '']
    lines = []
    for row in rows:
        lines.append("[[region]]")
        lines.append(f'name = "{row["name"]}"')
        lines.append(f'base = 0x{row["base"]:X}')
        lines.append(f'size = 0x{row["size"]:X}')
        if "attr" in row["attributes"]:
            lines.append(f'attribute = 0x{row["attributes"]["attr"]:X}')
        for key in sorted(row["attributes"]):
            if key != "attr":
                lines.append(f'{key} = 0x{row["attributes"][key]:X}')
        lines.append("")
    return out[0] + "\n" + out[1] + "\n" + out[2] + "\n" + "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Extract the DDR map from xbl_config.")
    parser.add_argument("blob", type=Path)
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--toml", action="store_true")
    parser.add_argument("--out", type=Path, help="write to this file instead of stdout")
    args = parser.parse_args()

    data = args.blob.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    rows = check(list(parse_entries(data)), args.blob)

    if args.json:
        text = as_json(rows, args.blob.name, digest)
    elif args.toml:
        text = as_toml(rows, args.blob.name, digest)
    else:
        text = f"# {args.blob.name}  sha256={digest[:16]}…  {len(rows)} regions\n"
        text += f"{'name':<20}{'base':>12}{'size':>12}{'end':>12}  attributes\n"
        for row in rows:
            attrs = " ".join(f"{key}=0x{value:X}" for key, value in sorted(row["attributes"].items()))
            text += (f'{row["name"]:<20}0x{row["base"]:>10X}0x{row["size"]:>10X}'
                     f'0x{row["base"] + row["size"]:>10X}  {attrs}\n')

    if args.out:
        args.out.write_text(text)
        print(f"wrote {args.out} ({len(rows)} regions)", file=sys.stderr)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
